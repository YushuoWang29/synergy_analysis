#!/usr/bin/env python
"""Compatibility wrapper for the retired short-report builder.

The current course deliverable is the LaTeX manuscript generated by
``build_course_paper.py`` and compiled with XeLaTeX.  This wrapper is kept so
older instructions fail gently instead of regenerating an obsolete report.
"""

from __future__ import annotations

from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[2]
PAPER_PDF = PROJECT_ROOT / "course_project" / "paper" / "course_paper.pdf"
PAPER_TEX = PROJECT_ROOT / "course_project" / "paper" / "course_paper.tex"


def main() -> None:
    print("The short ReportLab report has been retired.")
    print(f"Use the LaTeX course paper instead: {PAPER_TEX}")
    if PAPER_PDF.exists():
        print(f"Current PDF: {PAPER_PDF}")
    else:
        print("Run course_project/scripts/build_course_paper.py and XeLaTeX to build the PDF.")


if __name__ == "__main__":
    main()
